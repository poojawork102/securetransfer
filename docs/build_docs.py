def hamming74_table():
    rows = ["nibble  codeword (p1 p2 d1 p3 d2 d3 d4)   byte on wire"]
    for n in range(16):
        cw = P.hamming74_encode_nibble(n)
        rows.append(f"{n:04b}    {' '.join(f'{cw:07b}')}                      0x{cw:02x}")
    return "\n".join(rows)


def frame_dump():
    raw = P.build_frame(P.DATA, 3, b"HELLO")
    h = raw[:P.HEADER_SIZE]
    return (f"MAGIC  {h[0:2].hex()}  ('FT')\nVER    {h[2]:02x}  (protocol version 2)\nTYPE   {h[3]:02x}  (2 = DATA)\n"
            f"FLAGS  {h[4]:02x}  (no HMAC, no FEC, CRC32)\nSEQ    {h[5:9].hex()}  (chunk 3)\nLEN    {h[9:13].hex()}  (5 bytes)\n"
            f"CHECK  {h[13:17].hex()}  (CRC32 of 'HELLO')\nDATA   {raw[17:].hex()}  ('HELLO')\n\nfull frame: {raw.hex(' ')}")


def forge_demo():
    data = b"transfer 100 rupees to Pooja. " * 3
    raw = P.build_frame(P.DATA, 3, data, use_hmac=True, key=DOC_KEY)
    import socket
    a, b = socket.socketpair()
    a.sendall(raw)
    fr = P.read_frame(b)
    a.close(); b.close()
    forged = forge_chunk(fr, random.Random(0))
    got, status, _ = P.open_frame(forged, DOC_KEY)
    _, plain_status, _ = P.open_frame(P.Frame(forged.type, forged.flags & ~P.FLAG_HMAC, forged.seq, forged.crc, b"",
                                              forged.payload))      # same frame, HMAC ignored = a CRC-only receiver
    return (f"original : {data!r}\nforged   : {got!r}\n"
            f"CRC32 recomputed by the attacker: 0x{forged.crc:08x}  (valid: the receiver's CRC check "
            f"{'PASSES' if plain_status == P.OK else 'fails'})\n"
            f"HMAC attached to the frame is the OLD one -> receiver verdict with HMAC on: {status}")


def hmac_example():
    header = P.pack_header(P.DATA, P.FLAG_HMAC, 3, 5, P.crc32(b"HELLO"))
    mac = _hmac.new(DOC_KEY, header + b"HELLO", hashlib.sha256).digest()
    wrong = _hmac.new(b"attacker-guess", header + b"HELLO", hashlib.sha256).digest()
    return (f"key     = {DOC_KEY!r}\nmessage = header(17 bytes) || 'HELLO'\n"
            f"HMAC-SHA256 with the right key : {mac.hex()}\n"
            f"HMAC-SHA256 with a wrong key   : {wrong.hex()}\n"
            f"protocol.compute_hmac agrees   : {P.compute_hmac(DOC_KEY, header, b'HELLO') == mac}")


def sha256_example():
    a, b = b"Pay Pooja 100 rupees", b"Pay Pooja 900 rupees"
    ha, hb = hashlib.sha256(a).hexdigest(), hashlib.sha256(b).hexdigest()
    diff = bin(int(ha, 16) ^ int(hb, 16)).count("1")
    return (f"{a.decode():<22} -> {ha}\n{b.decode():<22} -> {hb}\n"
            f"one character changed -> {diff} of 256 hash bits differ (avalanche effect)")


def timeline_example():
    """Replay a scripted noisy-then-clean-then-attack link through the real rules engine."""
    mon = adaptive.Monitor(adaptive.Settings(fec=False, hmac=False, chunk_size=1024))
    out, seq = [], 0

    def feed(statuses):
        nonlocal seq
        for s in statuses:
            d = mon.record(seq, s)
            if d:
                out.append(f"chunk {seq:>3}  [{d.action}]  {d.reason}")
            if s in (adaptive.OK, adaptive.CORRECTED):
                seq += 1

    ok, bad, fix = adaptive.OK, adaptive.CHECK_FAIL, adaptive.CORRECTED
    feed(([ok, ok, bad, ok, ok, ok, bad] * 3))                 # noisy link: ~1 transmission in 4 fails the check
    feed(([fix, ok, ok, ok, ok, fix] * 3))                    # Hamming now repairs single bits
    feed([bad, bad, ok, bad, ok, bad, ok, bad, ok, bad])      # bursts Hamming cannot fix
    feed([ok] * 60)                                           # the link recovers
    mon.settings = adaptive.Settings(False, True, mon.settings.chunk_size)
    feed([adaptive.HMAC_FAIL, ok])                            # an attacker appears (HMAC now on)
    return "\n".join(out) + f"\nfinal protection: Hamming {'on' if mon.settings.fec else 'off'}, " \
                            f"HMAC {'on' if mon.settings.hmac else 'off'}, chunk {mon.settings.chunk_size} B"


