# ---------------------------------------------------------------------------- build
def fill(md):
    def sub(m):
        if m.group(2) not in GEN:
            raise KeyError(f"unknown generator {m.group(2)!r}")
        return f"{m.group(1)}\n```text\n{GEN[m.group(2)]().rstrip()}\n```\n{m.group(3)}"
    return MARK.sub(sub, md)


def doc_files():
    return sorted(glob.glob(os.path.join(ROOT, "docs", "concepts", "*.md"))) + [os.path.join(ROOT, "docs", "FACULTY_DEMO_GUIDE.md")]


def main(check=False):
    stale = []
    for path in doc_files():
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", newline="") as fh:
            old = fh.read()
        new = fill(old.replace("\r\n", "\n"))
        if new != old.replace("\r\n", "\n"):
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(new)
    if check:
        return stale
    guide = os.path.join(ROOT, "docs", "FACULTY_DEMO_GUIDE.md")
    if os.path.isfile(guide):
        with open(guide, encoding="utf-8") as fh:
            html = mdlite.render(fh.read(), "SecureTransfer — faculty demo guide")
        with open(os.path.join(ROOT, "docs", "FACULTY_DEMO_GUIDE.html"), "w", encoding="utf-8") as fh:
            fh.write(html)
    print("updated:", ", ".join(stale) if stale else "nothing to change")
    return stale


if __name__ == "__main__":
    if "--check" in sys.argv:
        s = main(check=True)
        print("out of date: " + ", ".join(s) if s else "all generated blocks are current")
        sys.exit(1 if s else 0)
    main()
